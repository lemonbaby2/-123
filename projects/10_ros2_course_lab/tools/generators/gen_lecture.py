code('θ ← θ + ω·Δt\nx  ← x + v·cos(θ)·Δt\ny  ← y + v·sin(θ)·Δt')
p('这就是轮式里程计（wheel odometry）的全部原理，一行不漏。它没有任何外部观测，只靠自己数轮子的转数，所以叫「航位推算」，英文 dead reckoning。这个词的本义是「推测航行」，用在机器人上特别传神：你闭上眼睛，凭自己走了多少步来猜自己在哪儿。步子数得再准，只要每一步有一点点偏差，走得越远偏得越离谱。')
p('我们的控制器以 100 Hz 做这件事，物理引擎的步长是 1 毫秒，也就是每 10 个物理步算一次控制。这个整除关系不是随便定的：如果控制周期和物理步长不成整数倍，会出现拍频，速度曲线上会看到周期性的抖动，学生往往以为是 PID 没调好，其实是节拍没对齐。')
