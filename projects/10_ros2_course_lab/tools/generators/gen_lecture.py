def render():
    doc = ak.new_doc() if hasattr(ak, 'new_doc') else None
    if doc is None:
        from docx_kit import new_doc
        doc = new_doc(header_text='第 12 周 · ROS 2 与机器人 · 教师演讲稿')
    else:
        doc = ak.new_doc(header_text='第 12 周 · ROS 2 与机器人 · 教师演讲稿')

    ak.cover2(
        doc,
        title='第 12 周课堂教学演讲稿',
        subtitle='运动学、里程计与 PID 控制 —— 含师生互问互答',
        fields=[
            ('课程名称', '机器学习与智能机器人应用技术'),
            ('适用周次', '第 12 周 · 2 学时（90 分钟）'),
            ('授课对象', '机器人工程 / 智能控制技术专业'),
            ('配套环境', 'Ubuntu 24.04 + ROS 2 Jazzy + Gazebo 8.11'),
            ('配套资源', 'W12 源码 + 网页看板 + 三张实拍截图'),
        ],
        date='2026 年 11 月',
    )

    # 封面 → 目录 → 正文，全部用显式分页符。
    # 不能用「段落 page_break_before」：Word 更新 TOC 域时会把域所在段落
    # 整个展开重写，分页属性会丢失，结果封面与目录挤在同一页、
    # 后面还多出一张纯空白页（本次实测踩到）。
    doc.add_page_break()
    add_toc(doc, levels='1-1')
    setup_toc_styles(doc)
    enable_update_fields(doc)
    add_footer_page_number(doc, prefix='— ', first_page_blank=True)
    doc.add_page_break()

    first_h1 = False
    for item in B:
        kind = item[0]
        if kind == 'h1':
            heading(doc, item[1], 1, pb=first_h1)
            first_h1 = False
        elif kind == 'h2':
            heading(doc, item[1], 2)
        elif kind == 'p':
            ak.para(doc, item[1])
        elif kind == 'b':
            ak.bullet2(doc, item[1])
        elif kind == 'code':
            code_block(doc, item[1])
        elif kind == 'table':
            _, cap, header, rows, widths, fs = item
            ak.table2(doc, [header] + rows, caption=cap,
                      widths=widths, font_size=fs)
        elif kind == 'qa':
            _, title, lines = item
            heading(doc, title, 2)
            for ln in lines:
                ak.para(doc, ln, indent=False, line=1.35)
        elif kind == 'note':
            _, lines, title, k = item
            ak.note(doc, lines, kind=k, title=title)
        elif kind == 'fig':
            _, path, cap = item
            if os.path.exists(path):
                figure(doc, path, cap, width_cm=15.0)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    doc.save(OUT)
    return doc


