h1('第一讲　差速运动学：两个轮子怎么算出整车速度')
h2('1.1 从「轮子转了多少」到「车走了多远」')
p('我们先把车拆到最简单。这台车只有两个驱动轮，前面一个万向球只负责支撑，不参与驱动。左轮和右轮各有一个电机、各有一个编码器。编码器能告诉我们的是轮子转了多少弧度，不是车走了多少米。中间的换算，就是本周第一个公式。')
p('设左轮线速度为 v_L、右轮线速度为 v_R，轮距（两个轮心之间的距离）为 L，车轮半径为 r。轮子不打滑时，车体中心的线速度是两个轮速的算术平均，车体绕自身中心旋转的角速度是两个轮速之差除以轮距：')
code('v   = (v_R + v_L) / 2\nω   = (v_R − v_L) / L\nv_L = ω_L · r ,   v_R = ω_R · r      （ω_L、ω_R 为编码器测得的轮角速度）')
p('这三个式子里藏着两个标定参数：轮半径 r 和轮距 L。我们这台车的实测配置是 r = 0.05 米、L = 0.36 米，写在 diffbot_controllers.yaml 里，和 URDF 的 xacro 属性一一对应。请大家现在打开这两个文件对照一遍——它们必须完全一致，改一处漏一处，车就立刻开始说谎。')
p('有同学会问，为什么角速度是差除以轮距，不是和除以轮距？画个图就明白了：两个轮子同速同向，差为零，车走直线；左轮慢右轮快，差为正，车向左偏；两个轮子一个正转一个反转，差最大，车原地打转。所谓差速，差的就是这一项。')
h2('1.2 从速度到位姿：里程计的积分')
